#!/usr/bin/env python3
"""Keep product identity independent of upstream file/protocol compatibility."""

from pathlib import Path
import plistlib
import re
import subprocess
import tempfile
import unittest
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]


def source(path):
    return (ROOT / path).read_text(encoding="utf-8")


class TinmanBrandingTests(unittest.TestCase):
    def setUp(self):
        self.settings = dict(re.findall(r'^set\((\w+) "([^"\n]+)"\)', source("version.inc"), re.M))

    def render(self, text):
        return re.sub(r'@(\w+)@', lambda match: self.settings[match[1]], text)

    def test_macos_bundle_uses_product_version(self):
        info = plistlib.loads(self.render(source("src/dev-utils/platform/osx/Info.plist.in")).encode())
        self.assertEqual(info["CFBundleIdentifier"], "com.tinmanfp.Tinman")
        self.assertEqual(info["CFBundleShortVersionString"], self.settings["TINMAN_MACOS_VERSION"])
        self.assertEqual(info["CFBundleVersion"], self.settings["TINMAN_MACOS_BUILD"])
        self.assertNotIn(self.settings["SoftFever_VERSION"], info["CFBundleGetInfoString"])
        for field in ("CFBundleVersion", "CFBundleShortVersionString"):
            self.assertRegex(info[field], r'^\d+\.\d+\.\d+$')

    def test_splash_and_diagnostics_use_tinman_version(self):
        app = source("src/slic3r/GUI/GUI_App.cpp")
        self.assertIn("version_display = TINMAN_DISPLAY_VERSION;", app)
        self.assertNotIn('m_text_version = _L("Based on Orca', app)
        for path in ("NetworkTestDialog.cpp", "TroubleshootDialog.cpp", "GCodeViewer.cpp"):
            text = source("src/slic3r/GUI/" + path)
            self.assertNotIn("SoftFever_VERSION", text, path)
            self.assertIn("TINMAN_VERSION", text, path)
        self.assertIn("TINMAN_DISPLAY_VERSION", source("src/slic3r/GUI/AboutDialog.cpp"))

    def test_compatibility_identity_is_not_calendar_version(self):
        self.assertEqual(self.settings["SLIC3R_APP_KEY"], "OrcaSlicer")
        self.assertEqual(self.settings["SoftFever_VERSION"], "2.4.2")
        self.assertNotEqual(self.settings["TINMANX1_PACKAGE_VERSION"], self.settings["SoftFever_VERSION"])
        gcode = source("src/libslic3r/GCode.cpp")
        self.assertIn('generated by OrcaSlicer %s on %s\\n", SoftFever_VERSION', gcode)
        self.assertNotIn("compat_version = tinman_generator", gcode)
        self.assertIn('SLIC3R_APP_NAME " " TINMAN_VERSION', source("src/libslic3r/utils.cpp"))
        project = source("src/libslic3r/Format/bbs_3mf.cpp")
        self.assertIn('xml_escape(SoftFever_VERSION)', project)
        self.assertIn('"OrcaSlicer-Version"', project)

    def test_artwork_has_no_frozen_version(self):
        for path in (ROOT / "resources/images").glob("*.svg"):
            if path.stem.startswith(("Tinman_about", "TinManX1_about", "splash_logo")):
                labels = " ".join(ET.fromstring(path.read_text()).itertext())
                self.assertNotIn("2.4.2", labels, str(path))
                self.assertNotRegex(labels, r'v2026\.', str(path))
                self.assertNotIn("TinManX1", labels, str(path))

    def test_linux_and_windows_package_identity(self):
        desktop = source("src/dev-utils/platform/unix/com.tinmanfp.Tinman.desktop")
        self.assertIn("Name=Tinman\n", desktop)
        self.assertIn("Exec=tinman %U", desktop)
        metadata = ET.fromstring(self.render(source("src/dev-utils/platform/unix/com.tinmanfp.Tinman.metainfo.xml.in")))
        self.assertEqual(metadata.findtext("id"), "com.tinmanfp.Tinman")
        self.assertEqual(metadata.find("releases/release").get("version"), self.settings["TINMANX1_PACKAGE_VERSION"])
        manifest = source("scripts/flatpak/com.tinmanfp.Tinman.yml")
        self.assertIn("app-id: com.tinmanfp.Tinman", manifest)
        self.assertIn("rename-icon: Tinman", manifest)
        self.assertIn("exec /app/bin/tinman", source("scripts/flatpak/entrypoint"))
        windows = source("scripts/msix/AppxManifest.xml")
        self.assertNotIn("TinManX1", windows)
        self.assertIn('Executable="Tinman.exe"', windows)
        self.assertIn('\\Tinman</virtualization:ExcludedDirectory>', windows)

    def test_release_workflow_does_not_reinstall_private_brand(self):
        build = source(".github/workflows/build_orca.yml")
        self.assertNotIn("install_orcaslicer_codex_app.py", build)
        self.assertIn("scripts/package_tinman_macos.py", build)
        for path in ("build_orca.yml", "publish_release.yml", "winget_updater.yml"):
            self.assertNotIn("TinManX1", source(".github/workflows/" + path))
        self.assertIn("bin/tinman", build)

    def test_packager_rejects_stale_bundle_before_writing(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            contents = root / "Old.app/Contents"
            contents.mkdir(parents=True)
            (contents / "Info.plist").write_bytes(plistlib.dumps({"CFBundleVersion": "2.4.2", "CFBundleShortVersionString": "2.4.2"}))
            result = subprocess.run(["python3", str(ROOT / "scripts/package_tinman_macos.py"),
                                     "--source-app", str(contents.parent), "--output-dir", str(root / "out")],
                                    capture_output=True, text=True)
            self.assertNotEqual(result.returncode, 0)
            self.assertIn("Stale build", result.stderr)
            self.assertFalse((root / "out").exists())


if __name__ == "__main__":
    unittest.main()
