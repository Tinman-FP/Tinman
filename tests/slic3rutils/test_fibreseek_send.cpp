// The mock printer's interpreter and script. CI sets TINMAN_REQUIRE_FIBRESEEK_MOCK
// so a missing one fails instead of skipping the end-to-end tests.
//
// Since 2.5.1 the unit tests run on every platform's CI runner, not only Linux,
// so a candidate must really run Python 3: on Windows, python3.exe can be the
// Microsoft Store stub, which exists but only prints an install hint.
bool python_runs_mock(const std::string &python)
{
    boost::system::error_code exists_ec;
    if (python.empty() || !fs::exists(python, exists_ec))
        return false;
    std::error_code ec;
    const int       code = boost::process::system(python, "-c", "import http.server, sys; sys.exit(sys.version_info[0] != 3)",
                                                  boost::process::std_out > boost::process::null,
                                                  boost::process::std_err > boost::process::null, ec);
    return !ec && code == 0;
}

std::string find_mock_python()
{
    if (const char *env = std::getenv("FIBRESEEK_MOCK_PYTHON"))
        return env;
    std::vector<std::string> candidates;
#ifdef FIBRESEEK_MOCK_PYTHON
    candidates.emplace_back(FIBRESEEK_MOCK_PYTHON);
#endif
    for (const char *name : {"python3", "python"})
        candidates.push_back(boost::process::search_path(name).string());
    for (const std::string &candidate : candidates)
        if (python_runs_mock(candidate))
            return candidate;
    return {};
}

std::string mock_python()
{
    static const std::string python = find_mock_python();
    return python;
}

// Set and not "0". The workflow passes "0" where Python may be missing (Windows).
bool mock_required()
{
    const char *value = std::getenv("TINMAN_REQUIRE_FIBRESEEK_MOCK");
    return value != nullptr && *value != '\0' && std::string(value) != "0";
}

std::string mock_script()
{
    if (const char *env = std::getenv("FIBRESEEK_MOCK_SCRIPT"))
        return env;
    return FIBRESEEK_MOCK_SCRIPT;
}

// Runs fibreseek_mock_moonraker.py on a free 127.0.0.1 port for one test case.
class MockPrinter
{
public:
    MockPrinter()
    {
        const fs::path dir = fs::temp_directory_path() / fs::unique_path("tinman-fs3-mock-%%%%%%%%");
        fs::create_directories(dir);
        m_port_file = dir / "port";
        m_child = boost::process::child(mock_python(), mock_script(), "--port", "0", "--port-file",
                                        m_port_file.string(), boost::process::std_out > boost::process::null);
        for (int i = 0; i < 100 && m_port.empty(); ++i) {
            std::this_thread::sleep_for(std::chrono::milliseconds(100));
            if (fs::exists(m_port_file))
                fs::ifstream(m_port_file) >> m_port;
        }
    }
    ~MockPrinter()
    {
        std::error_code ec;
        m_child.terminate(ec);
        boost::system::error_code bec;
        fs::remove_all(m_port_file.parent_path(), bec);
    }
    bool        running() const { return !m_port.empty(); }
    std::string address() const { return "127.0.0.1:" + m_port; }

    void set(const json &state) const
    {
        Http::post("http://" + address() + "/_mock/state").header("Content-Type", "application/json").set_post_body(state.dump()).perform_sync();
    }
    json log() const
    {
        std::string body;
        Http::get("http://" + address() + "/_mock/log").on_complete([&](std::string reply, unsigned) { body = reply; }).perform_sync();
        return json::parse(body);
    }
    // Requests the host made, as "METHOD /path".
    std::vector<std::string> calls() const
    {
        std::vector<std::string> out;
        const json               all = log(); // keep the reply alive while iterating its members
        for (const auto &request : all["requests"])
            out.push_back(request["method"].get<std::string>() + " " + request["path"].get<std::string>());
        return out;
    }
    size_t count(const std::string &call) const
    {
        const auto all = calls();
        return size_t(std::count(all.begin(), all.end(), call));
    }
    size_t uploads() const { return count("POST /server/files/upload"); }
    size_t starts() const { return log()["starts"].size(); }

private:
    fs::path              m_port_file;
    std::string           m_port;
    boost::process::child m_child;
};

struct SendResult
{
    bool     ok = false;
    wxString error;
    bool     acknowledged_cancel = false; // the host told the queue "Canceled"
};

// The percent the host shows between phases (FibreSeek.cpp): 92 verify, 95 start, 97 watch.
bool at_percent(const Http::Progress &p, size_t percent) { return p.ultotal == 100 && p.ulnow == percent; }

// A FibreSeek host for the mock, with short timeouts.
std::unique_ptr<FibreSeek> make_host(const MockPrinter &printer, int start_watch = 3, int preprint_watch = 6)
{
    DynamicPrintConfig config;
    config.set_deserialize_strict({{"print_host", printer.address()}, {"printhost_apikey", "test-key"},
                                   {"printhost_cafile", ""}, {"printhost_ssl_ignore_revoke", "0"}});
    auto                host = std::make_unique<FibreSeek>(&config);
    FibreSeek::Timeouts timeouts;
    timeouts.query       = 2;
    timeouts.start       = 2;
    timeouts.start_watch    = start_watch;
    timeouts.preprint_watch = preprint_watch;
    timeouts.poll_ms        = 200;
    host->set_timeouts(timeouts);
    return host;
}

// cancel_when(progress) returning true cancels the send at that progress call.
SendResult send(const MockPrinter &printer, const fs::path &file, PrintHostPostUploadAction action,
                std::function<bool(const Http::Progress &)> cancel_when = nullptr, int start_watch = 3, int preprint_watch = 6)
{
    const auto host = make_host(printer, start_watch, preprint_watch);
    PrintHostUpload upload;
    upload.source_path = file;
    upload.upload_path = file.filename();
    upload.post_action = action;
    SendResult result;
    result.ok = host->upload(
        upload,
        [&](Http::Progress progress, bool &cancel) {
            if (cancel) { // the queue's "Canceled" acknowledgement
                result.acknowledged_cancel = true;
                return;
            }
            CHECK((progress.ultotal == 0 || progress.ulnow < progress.ultotal)); // never 100% before the outcome
            if (cancel_when && cancel_when(progress))
                cancel = true;
        },
        [&](wxString error) { result.error = error; }, [](wxString, wxString) {});
    return result;
}

bool contains(const std::vector<std::string> &calls, const std::string &call)
{
    return std::find(calls.begin(), calls.end(), call) != calls.end();
}

