// A temporary file that is removed when the test ends.
struct TempFile
{
    fs::path path;
    explicit TempFile(const std::string &contents, const std::string &name = "job.gcode")
        : path(fs::temp_directory_path() / fs::unique_path("tinman-fs3-%%%%%%%%") / name)
    {
        fs::create_directories(path.parent_path());
        fs::ofstream(path, std::ios::binary) << contents;
    }
    ~TempFile()
    {
        boost::system::error_code ec;
        fs::remove_all(path.parent_path(), ec);
    }
};

// The parts of a Tinman Seeker 3 job the host reads: fibre commands and the config block.
std::string seeker3_gcode(const std::string &nozzles = "0.4,0.7", const std::string &model = "FibreSeek Seeker 3",
                          const std::string &plastic = "0.4", const std::string &composite = "0.7")
{
    return "; generated by Tinman\nG28\nG1 X10 Y10 E1\nM1001\nG1 X20 Y10\nM2800\nM1002\n"
           "; CONFIG_BLOCK_START\n; composite_nozzle_diameter = " + composite + "\n; nozzle_diameter = " + nozzles +
           "\n; plastic_nozzle_diameter = " + plastic + "\n; printer_model = " + model + "\n; CONFIG_BLOCK_END\n";
}

std::string query(const json &status) { return json{{"result", {{"eventtime", 1.0}, {"status", status}}}}.dump(); }

JobInfo job(std::vector<double> nozzles, double plastic, double composite, bool fibre)
{
    JobInfo out;
    out.nozzle_diameters = std::move(nozzles);
    out.plastic_nozzle   = plastic;
    out.composite_nozzle = composite;
    out.continuous_fiber = fibre;
    return out;
}

